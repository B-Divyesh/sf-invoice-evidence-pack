import { chromium } from 'playwright';

const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const errors = [];
const requests = [];
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
page.on('pageerror', error => errors.push(`pageerror: ${error.message}`));
page.on('request', request => requests.push(request.url()));

await page.goto('http://127.0.0.1:4174/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Start your first packet' }).press('Enter');
await page.getByRole('button', { name: 'Create packet' }).click();
const invalidMessage = await page.locator('input[name="title"]').evaluate(input => input.validationMessage);
if (!invalidMessage) throw new Error('required packet-name input lacks native invalid state');
await page.getByLabel('Packet name Required').fill('Boundary & recovery packet');
await page.getByLabel('Invoice number').fill('INV-000');
await page.getByLabel('Client or counterparty').fill('A < B & C');
await page.getByLabel('Jurisdiction or review context').fill('Cross-border client review');
await page.getByLabel('Currency').fill('inr');
await page.getByRole('button', { name: 'Create packet' }).click();
await page.getByLabel('Accountant or reviewer notes').fill('Payment is intentionally pending. Please review the signed work log.');
await page.getByLabel('Accountant or reviewer notes').press('Tab');
const active = await page.evaluate(() => { const element = document.activeElement; return { tag: element?.tagName, outline: element ? getComputedStyle(element).outlineStyle : '', width: element ? getComputedStyle(element).outlineWidth : '' }; });
const focusLostAfterAutosave = active.tag === 'BODY';
await page.locator('input[type="file"][data-item]').first().setInputFiles({ name: 'invoice-000.txt', mimeType: 'text/plain', buffer: Buffer.from('normal representative evidence') });
await page.getByText('Evidence stored locally and fingerprinted.').waitFor();
await page.locator('input[type="file"][data-item]').nth(1).setInputFiles('/tmp/invoice-too-large.bin');
await page.getByText('That file is over the 100 MB per-file limit. Choose a smaller file.').waitFor();
let confirmText = '';
page.once('dialog', dialog => { confirmText = dialog.message(); return dialog.dismiss(); });
await page.getByRole('button', { name: 'Export ZIP packet' }).click();
if (!confirmText.includes('missing')) throw new Error('incomplete export did not explain missing items');
await page.getByRole('button', { name: 'Add checklist item' }).click();
await page.getByRole('button', { name: 'Add item' }).click();
const itemMessage = await page.locator('input[name="label"]').evaluate(input => input.validationMessage);
if (!itemMessage) throw new Error('required checklist label lacks invalid state');
await page.locator('dialog[open] [aria-label="Close dialog"]').click();
await page.getByRole('button', { name: 'Import backup' }).click();
const importInput = page.locator('#backup-input');
page.once('dialog', dialog => dialog.accept());
await importInput.setInputFiles({ name: 'invalid-backup.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}') });
await page.getByText('This is not a supported Invoice Packet backup.').waitFor();
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('heading', { name: 'Boundary & recovery packet' }).waitFor();
await page.emulateMedia({ reducedMotion: 'reduce' });
const reduced = await page.locator('.button').first().evaluate(el => getComputedStyle(el).transitionDuration);
if (!['0.00001s', '1e-05s'].includes(reduced)) throw new Error(`reduced motion transition was ${reduced}`);
const storage = await page.evaluate(async () => ({ local: Object.keys(localStorage), dbs: await indexedDB.databases().then(rows => rows.map(row => row.name)) }));
await page.screenshot({ path: '/tmp/invoice-desktop.png', fullPage: true });
await context.setOffline(true);
await page.reload({ waitUntil: 'domcontentloaded' });
await page.getByRole('heading', { name: 'Boundary & recovery packet' }).waitFor();
await context.setOffline(false);
await browser.close();
console.log(JSON.stringify({ invalidMessage, itemMessage, active, focusLostAfterAutosave, reduced, storage, consoleErrors: errors, externalRequests: [...new Set(requests.filter(url => !url.startsWith('http://127.0.0.1:4174')))] }, null, 2));
